import 'package:flutter/material.dart';
import 'package:flutter_markdown/flutter_markdown.dart';

/// Renders assistant (and user) chat messages with proper Markdown formatting.
/// Supports bold (**text**), italics (*text*), unordered lists (- item),
/// numbered lists (1. item), headings (#, ##), inline code, blockquotes, and links.
/// Automatically cleans and normalizes malformed AI output (e.g. ***bold**, unicode bullets).
class MarkdownMessageView extends StatelessWidget {
  final String text;
  final bool isUser;
  final TextStyle? baseStyle;
  final void Function(String url)? onLinkTap;

  const MarkdownMessageView({
    super.key,
    required this.text,
    this.isUser = false,
    this.baseStyle,
    this.onLinkTap,
  });

  /// Normalizes and cleans malformed markdown generated by AI/LLMs or legacy knowledge bases.
  /// Does NOT blindly strip asterisks; instead fixes unbalanced or malformed markdown syntax.
  static String sanitizeMarkdown(String input) {
    if (input.isEmpty) return input;

    final lines = input.split('\n');
    final processedLines = <String>[];
    bool inList = false;

    for (var i = 0; i < lines.length; i++) {
      var line = lines[i].trimRight();

      // 1. Fix malformed affiliation missing colon/unbalanced asterisks:
      // e.g. **Affiliation Constituent institute of **Uka... -> - **Affiliation:** Constituent institute of Uka...
      if (line.contains('**Affiliation Constituent institute of **')) {
        line = line.replaceFirst(
          '**Affiliation Constituent institute of **',
          '- **Affiliation:** Constituent institute of **',
        );
      }

      // 2. Fix 3+ star bold prefix at start of line e.g. ***Programmes Offered:** -> - **Programmes Offered:**
      line = line.replaceAllMapped(
        RegExp(r'^\s*\*+\s*([a-zA-Z0-9_\s&/().,-]+?)\s*\*+:'),
        (m) => '- **${m[1]}:**',
      );

      // 3. Clean any other occurrence of 3+ asterisks down to standard double asterisks
      line = line.replaceAllMapped(RegExp(r'\*{3,}'), (m) => '**');

      // 4. Normalize bullets (•, ●, etc. or *) to `- `
      final bulletMatch = RegExp(r'^\s*([•●○■◆]|\*|-)\s+(.*)$').firstMatch(line);
      if (bulletMatch != null) {
        final content = bulletMatch.group(2) ?? '';
        line = '- $content';

        // Add a single blank line before the start of a list block if preceded by text
        if (!inList && processedLines.isNotEmpty && processedLines.last.trim().isNotEmpty) {
          processedLines.add('');
        }
        inList = true;
      } else {
        // If a line is formatted as a bold label e.g. **Label:** and we are in a list, format as list item
        if (inList && RegExp(r'^\s*\*\*[^\*\n]+:\*\*').hasMatch(line)) {
          line = '- $line';
        } else if (line.trim().isEmpty) {
          inList = false;
        } else {
          inList = false;
        }
      }

      processedLines.add(line);
    }

    return processedLines.join('\n');
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final defaultColor = isUser ? Colors.white : Colors.black87;
    final textStyle = baseStyle ??
        TextStyle(
          color: defaultColor,
          fontSize: 14.5,
          height: 1.45,
        );

    final cleanText = sanitizeMarkdown(text);

    return MarkdownBody(
      data: cleanText,
      selectable: false,
      styleSheet: MarkdownStyleSheet.fromTheme(theme).copyWith(
        p: textStyle,
        pPadding: const EdgeInsets.only(bottom: 6),
        strong: textStyle.copyWith(
          fontWeight: FontWeight.bold,
          color: isUser
              ? Colors.white
              : (theme.brightness == Brightness.dark ? Colors.white : const Color(0xFF0F172A)),
        ),
        em: textStyle.copyWith(fontStyle: FontStyle.italic),
        h1: textStyle.copyWith(fontSize: 18, fontWeight: FontWeight.bold),
        h2: textStyle.copyWith(fontSize: 16, fontWeight: FontWeight.bold),
        h3: textStyle.copyWith(fontSize: 15, fontWeight: FontWeight.bold),
        listBullet: textStyle.copyWith(
          color: isUser
              ? Colors.white
              : (theme.brightness == Brightness.dark ? Colors.white70 : const Color(0xFF1E293B)),
          fontWeight: FontWeight.bold,
        ),
        listBulletPadding: const EdgeInsets.only(right: 6),
        listIndent: 16,
        blockSpacing: 8,
        code: TextStyle(
          fontFamily: 'monospace',
          fontSize: 13,
          color: isUser ? Colors.white : const Color(0xFF0F172A),
          backgroundColor: isUser ? Colors.white24 : Colors.grey.shade200,
        ),
        codeblockDecoration: BoxDecoration(
          color: isUser ? Colors.white12 : Colors.grey.shade100,
          borderRadius: BorderRadius.circular(8),
          border: Border.all(color: Colors.grey.shade300),
        ),
        a: TextStyle(
          color: isUser ? Colors.white : const Color(0xFF1D4ED8),
          decoration: TextDecoration.underline,
          fontWeight: FontWeight.w600,
        ),
      ),
      onTapLink: (text, href, title) {
        if (onLinkTap != null && href != null) {
          onLinkTap!(href);
        }
      },
    );
  }
}
