import re

def sanitize_markdown(text: str) -> str:
    """
    Normalizes and cleans malformed markdown generated by AI/LLMs or legacy knowledge bases.
    Does NOT blindly strip asterisks; instead fixes unbalanced or malformed markdown syntax.
    """
    if not text:
        return ""

    lines = text.split("\n")
    processed_lines = []
    in_list = False

    for line in lines:
        rline = line.rstrip()

        # 1. Fix malformed affiliation missing colon/unbalanced asterisks
        if "**Affiliation Constituent institute of **" in rline:
            rline = rline.replace(
                "**Affiliation Constituent institute of **",
                "- **Affiliation:** Constituent institute of "
            )

        # 2. Fix 3+ star bold prefix at start of line e.g. ***Programmes Offered:** -> - **Programmes Offered:**
        rline = re.sub(r'^\s*\*+\s*([a-zA-Z0-9_\s&/().,-]+?)\s*\*+:', r'- **\1:**', rline)

        # 3. Clean any other occurrence of 3+ asterisks down to standard double asterisks
        rline = re.sub(r'\*{3,}', '**', rline)

        # 4. Normalize bullets (•, ●, etc. or *) to `- `
        bullet_match = re.match(r'^\s*([•●○■◆]|\*|-)\s+(.*)$', rline)
        if bullet_match:
            content = bullet_match.group(2) or ''
            rline = f"- {content}"
            if not in_list and processed_lines and processed_lines[-1].strip():
                processed_lines.append("")
            in_list = True
        else:
            if in_list and re.match(r'^\s*\*\*[^\*\n]+:\*\*', rline):
                rline = f"- {rline}"
            elif not rline.strip():
                in_list = False
            else:
                in_list = False

        processed_lines.append(rline)

    return "\n".join(processed_lines)
